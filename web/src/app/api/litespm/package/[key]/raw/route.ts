import { NextRequest, NextResponse } from "next/server";
import { getPackageDetail } from "@/server/litespm/package-detail";
import { displayPackageName } from "@/lib/litespm/format";

export const dynamic = "force-dynamic";

interface Props {
  params: Promise<{ key: string }>;
}

export async function GET(request: NextRequest, { params }: Props) {
  const { key } = await params;
  if (!key) {
    return new NextResponse("# Invalid Package Key\n", { status: 400, headers: { "Content-Type": "text/markdown; charset=utf-8" } });
  }

  const detail = await getPackageDetail(decodeURIComponent(key));
  if (!detail.found || !detail.detail) {
    return new NextResponse(`# Package Not Found\n\nThe requested package \`${key}\` was not found in the LiteSPM catalog.\n`, {
      status: 404,
      headers: { "Content-Type": "text/markdown; charset=utf-8" },
    });
  }

  const p = detail.detail;
  const name = displayPackageName(p.name);
  const installCmd = `litespm install ${p.id}`;

  const markdown = `# ${name}

> ${p.summary || "No description provided."}

- **Package ID:** \`${p.id}\`
- **Kind:** ${p.kind}
- **Publisher:** ${p.publisher.name}${p.publisher.verified ? " (Verified)" : ""}
- **Score:** ${typeof p.rankScore === "number" ? `${Math.round(p.rankScore)}/100` : "N/A"}
- **Installable:** ${p.installable ? "Yes" : "Discovery-only (Manual configuration)"}

## Installation

\`\`\`bash
${installCmd}
\`\`\`

## Upstream & Source
- **Repository:** ${p.repoUrl || p.source || "Not specified"}
- **Version:** ${p.version || "latest"}

---
*Generated by LiteSPM catalog exporter (https://lite-spm-nine.vercel.app)*
`;

  return new NextResponse(markdown, {
    status: 200,
    headers: {
      "Content-Type": "text/markdown; charset=utf-8",
      "Cache-Control": "public, max-age=3600, s-maxage=3600",
    },
  });
}
