/**
 * BM25F index over the catalog, built once per process.
 *
 * The old ranker gave a fixed weight to the first field that matched. That
 * over-rewards common words and has no document-frequency signal: "server"
 * looked as informative as "postgres". BM25F fixes both, and the field weights
 * keep a name match stronger than a summary mention.
 *
 * The index stores one compact token string per field rather than a postings
 * map. At 69k rows that is far less memory than a Map<token, postings[]> and
 * still scores a query in milliseconds, because the strings are already
 * normalized and padded for token counting.
 */

import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { gunzipSync } from "node:zlib";

import type { Listing } from "./types";
import { countToken, queryGroups, tokenCount, tokenField } from "./text";

export interface SearchDoc {
  name: string;
  slug: string;
  nameTokens: string;
  publisherTokens: string;
  summaryTokens: string;
  categoryTokens: string;
  metaTokens: string;
  /** Weighted field length used by BM25's length normalization. */
  len: number;
}

export interface SearchIndex {
  releaseId: string;
  docs: Map<string, SearchDoc>;
  rowIds: string[];
  /** token -> row indexes that contain it. Candidate generation, not scoring. */
  postings: Map<string, number[]>;
  df: Map<string, number>;
  avgLen: number;
  n: number;
}

/**
 * Compact on-disk form. Tuples keep the JSON small enough to gzip to a few
 * megabytes; the runtime expands them back into the Maps `scoreDoc` expects.
 */
type SerializedDoc = [
  id: string,
  name: string,
  slug: string,
  nameTokens: string,
  publisherTokens: string,
  summaryTokens: string,
  categoryTokens: string,
  metaTokens: string,
  len: number,
];

export interface SerializedSearchIndex {
  version: 1;
  releaseId: string;
  docs: SerializedDoc[];
  postings: Record<string, number[]>;
  df: Record<string, number>;
  avgLen: number;
  n: number;
}

export function serializeSearchIndex(index: SearchIndex): SerializedSearchIndex {
  const docs: SerializedDoc[] = index.rowIds.map((id) => {
    const doc = index.docs.get(id)!;
    return [
      id,
      doc.name,
      doc.slug,
      doc.nameTokens,
      doc.publisherTokens,
      doc.summaryTokens,
      doc.categoryTokens,
      doc.metaTokens,
      doc.len,
    ];
  });
  const postings: Record<string, number[]> = {};
  for (const [token, rows] of index.postings) postings[token] = rows;
  const df: Record<string, number> = {};
  for (const [token, count] of index.df) df[token] = count;
  return {
    version: 1,
    releaseId: index.releaseId,
    docs,
    postings,
    df,
    avgLen: index.avgLen,
    n: index.n,
  };
}

function deserializeSearchIndex(serialized: SerializedSearchIndex): SearchIndex {
  const docs = new Map<string, SearchDoc>();
  const rowIds: string[] = [];
  for (const tuple of serialized.docs) {
    const [id, name, slug, nameTokens, publisherTokens, summaryTokens, categoryTokens, metaTokens, len] = tuple;
    docs.set(id, { name, slug, nameTokens, publisherTokens, summaryTokens, categoryTokens, metaTokens, len });
    rowIds.push(id);
  }
  return {
    releaseId: serialized.releaseId,
    docs,
    rowIds,
    postings: new Map(Object.entries(serialized.postings)),
    df: new Map(Object.entries(serialized.df)),
    avgLen: serialized.avgLen,
    n: serialized.n,
  };
}

function indexDataDir(): string {
  const direct = path.join(process.cwd(), "data");
  if (existsSync(path.join(direct, "search-index.json.gz"))) return direct;
  return path.join(process.cwd(), "data", "litespm");
}

/**
 * Load the build-time index if it matches this catalog release. The gzip file
 * is generated by `scripts/build-search-index.mjs`; a missing or stale file
 * falls back to the in-memory build, which is slower but still correct.
 */
function loadSerializedIndex(releaseId: string): SearchIndex | null {
  const file = path.join(indexDataDir(), "search-index.json.gz");
  if (!existsSync(file)) return null;
  try {
    const serialized = JSON.parse(gunzipSync(readFileSync(file)).toString("utf8")) as SerializedSearchIndex;
    if (serialized.version !== 1 || serialized.releaseId !== releaseId) return null;
    const index = deserializeSearchIndex(serialized);
    console.info(`[catalog-search] loaded precomputed BM25F index for ${index.n} rows`);
    return index;
  } catch (error) {
    console.warn("[catalog-search] precomputed index could not be loaded; rebuilding", error);
    return null;
  }
}

const FIELD_WEIGHTS = {
  name: 4,
  publisher: 2,
  summary: 1.5,
  category: 1.2,
  meta: 1,
} as const;

const K1 = 1.2;
const B = 0.75;

const globalForIndex = globalThis as unknown as {
  __litespmBm25?: SearchIndex;
};

// HMR keeps globalThis across edits; a stale index built by older tokenizer
// rules would silently serve wrong results. Production keeps the warm copy.
if (process.env.NODE_ENV !== "production") {
  globalForIndex.__litespmBm25 = undefined;
}

/** Build (or reuse) the index for one catalog release. */
export function getSearchIndex(rows: Listing[], releaseId: string): SearchIndex {
  const startedAt = Date.now();
  const cached = globalForIndex.__litespmBm25;
  if (cached && cached.releaseId === releaseId && cached.postings && cached.rowIds) {
    return cached;
  }

  const loaded = loadSerializedIndex(releaseId);
  if (loaded) {
    globalForIndex.__litespmBm25 = loaded;
    return loaded;
  }

  const docs = new Map<string, SearchDoc>();
  const rowIds: string[] = [];
  const postings = new Map<string, number[]>();
  const df = new Map<string, number>();
  let totalLen = 0;

  for (const [rowIndex, row] of rows.entries()) {
    const nameTokens = tokenField(`${row.name} ${row.slug}`, 80);
    const publisherTokens = tokenField(row.publisher?.name ?? "", 40);
    // Summaries are long; the first 140 tokens carry the meaning and keep the
    // index compact.
    const summaryTokens = tokenField(row.summary ?? "", 100);
    const categoryTokens = tokenField(row.category ?? "", 40);
    const metaTokens = tokenField(
      [
        row.transport ?? "",
        row.runtime ?? "",
        row.command ?? "",
        ...(row.args ?? []),
        ...(row.tools ?? []).map((tool) => `${tool.name} ${tool.description}`),
        row.installHint ?? "",
      ].join(" "),
      80,
    );

    const len =
      tokenCount(nameTokens) * FIELD_WEIGHTS.name +
      tokenCount(publisherTokens) * FIELD_WEIGHTS.publisher +
      tokenCount(summaryTokens) * FIELD_WEIGHTS.summary +
      tokenCount(categoryTokens) * FIELD_WEIGHTS.category +
      tokenCount(metaTokens) * FIELD_WEIGHTS.meta;
    totalLen += len;

    docs.set(row.id, {
      name: row.name.toLowerCase(),
      slug: row.slug.toLowerCase(),
      nameTokens,
      publisherTokens,
      summaryTokens,
      categoryTokens,
      metaTokens,
      len,
    });
    rowIds.push(row.id);

    // Document frequency and the candidate postings come from the unique
    // tokens of this row. A Set per row is temporary; the index keeps only
    // the global maps and the normalized field strings.
    const unique = new Set<string>();
    for (const field of [nameTokens, publisherTokens, summaryTokens, categoryTokens, metaTokens]) {
      for (const token of field.trim().split(" ")) {
        if (token) unique.add(token);
      }
    }
    for (const token of unique) {
      df.set(token, (df.get(token) ?? 0) + 1);
      const bucket = postings.get(token);
      if (bucket) bucket.push(rowIndex);
      else postings.set(token, [rowIndex]);
    }
  }

  const index: SearchIndex = {
    releaseId,
    docs,
    rowIds,
    postings,
    df,
    avgLen: rows.length > 0 ? Math.max(1, totalLen / rows.length) : 1,
    n: rows.length,
  };
  globalForIndex.__litespmBm25 = index;
  console.info(
    `[catalog-search] built BM25F index for ${rows.length} rows in ${Date.now() - startedAt}ms`,
  );
  return index;
}

function weightedTf(doc: SearchDoc, token: string): number {
  return (
    countToken(doc.nameTokens, token) * FIELD_WEIGHTS.name +
    countToken(doc.publisherTokens, token) * FIELD_WEIGHTS.publisher +
    countToken(doc.summaryTokens, token) * FIELD_WEIGHTS.summary +
    countToken(doc.categoryTokens, token) * FIELD_WEIGHTS.category +
    countToken(doc.metaTokens, token) * FIELD_WEIGHTS.meta
  );
}

function bm25(tf: number, df: number, n: number, docLen: number, avgLen: number): number {
  if (tf <= 0 || df <= 0) return 0;
  const idf = Math.log(1 + (n - df + 0.5) / (df + 0.5));
  const norm = K1 * (1 - B + (B * docLen) / avgLen);
  return (idf * (tf * (K1 + 1))) / (tf + norm);
}

const normalizeName = (s: string) => s.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, "");

/**
 * Score one document against query groups. Every group must match at least
 * one term, so "postgres drizzle" does not match every Postgres row.
 */
export function scoreDoc(
  doc: SearchDoc,
  groups: string[][],
  index: SearchIndex,
  installable = false,
  transport = false,
): number {
  if (groups.length === 0) return 0;
  let total = 0;

  for (const group of groups) {
    let best = 0;
    for (const term of group) {
      const tf = weightedTf(doc, term);
      if (tf === 0) continue;
      const score = bm25(tf, index.df.get(term) ?? 0, index.n, doc.len, index.avgLen);
      if (score > best) best = score;
    }
    if (best === 0) return 0;
    total += best;
  }

  // Exact/prefix name and slug evidence still matters more than a bag of
  // words; these bonuses are deliberately small next to BM25's IDF mass.
  const queryName = groups.map((group) => group[0]).join(" ");
  const name = normalizeName(doc.name);
  const slug = normalizeName(doc.slug);
  const q = normalizeName(queryName);
  if (q.length > 0) {
    if (name === q || slug === q) total += 90;
    else if (name.startsWith(q)) total += 40;
    else if (name.includes(q) || slug.includes(q)) total += 18;
  }
  if (installable) total += 6;
  if (transport) total += 2;
  return total;
}

/**
 * Rows that contain at least one term from every query group. Returning null
 * means "no constraint" (the query had no searchable tokens). This is what
 * keeps a query from scanning all 69k documents: a specific term touches only
 * its posting list, and multi-term questions intersect those lists.
 */
export function candidateRowIds(index: SearchIndex, groups: string[][]): Set<string> | null {
  if (groups.length === 0) return null;
  let intersection: Set<number> | null = null;

  for (const group of groups) {
    const groupRows = new Set<number>();
    for (const term of group) {
      for (const rowIndex of index.postings.get(term) ?? []) groupRows.add(rowIndex);
    }
    if (groupRows.size === 0) return new Set();
    if (intersection === null) {
      intersection = groupRows;
      continue;
    }
    for (const rowIndex of intersection) {
      if (!groupRows.has(rowIndex)) intersection.delete(rowIndex);
    }
    if (intersection.size === 0) return new Set<string>();
  }

  const out = new Set<string>();
  for (const rowIndex of intersection ?? []) {
    const id = index.rowIds[rowIndex];
    if (id) out.add(id);
  }
  return out;
}

