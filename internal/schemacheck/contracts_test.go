// loadSchema reads a committed schema relative to this test file, the way
// internal/catalogbuild/dataset_test.go reads its fixtures.
func loadSchema(t *testing.T, name string) *schemacheck.Schema {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("..", "..", "schemas", name))
	if err != nil {
		t.Fatalf("read schema %s: %v", name, err)
	}
	s, err := schemacheck.Parse(raw)
	if err != nil {
		t.Fatalf("parse schema %s: %v", name, err)
	}
	return s
}

func decodeArray(t *testing.T, what string, raw []byte) []any {
	t.Helper()
	v, err := schemacheck.Decode(raw)
	if err != nil {
		t.Fatalf("decode %s: %v", what, err)
	}
	arr, ok := v.([]any)
	if !ok {
		t.Fatalf("%s: expected a JSON array, got %T", what, v)
	}
	return arr
}

// TestCommittedReleaseTreeValidates validates the real artifacts published
// under web/public/v1/releases/ (read-only) against the committed schemas.
func TestCommittedReleaseTreeValidates(t *testing.T) {
	releaseSchema := loadSchema(t, "catalog-release.schema.json")
	listingSchema := loadSchema(t, "listing.schema.json")
	versionSchema := loadSchema(t, "version.schema.json")

	root := filepath.Join("..", "..", "web", "public", "v1", "releases")
	entries, err := os.ReadDir(root)
	if err != nil {
		if os.IsNotExist(err) {
			// web/public/v1/releases/ is generated by `litespm catalog build`
			// at release/deploy time and is gitignored (the committed artifact
			// is the pointer web/public/v1/current.json), so a clean checkout
			// has no tree to check. The freshly compiled release in
			// TestCompileReleaseOutputValidates covers this contract either
			// way; skip rather than fail a checkout that never materialized it.
			t.Skipf("no materialized release tree at %s (gitignored; built by `litespm catalog build`)", root)
		}
		t.Fatalf("read release tree %s: %v", root, err)
	}

	releases := 0
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		releases++
		dir := filepath.Join(root, e.Name())

		manifest, err := os.ReadFile(filepath.Join(dir, "manifest.json"))
		if err != nil {
			t.Fatalf("%s: read manifest: %v", e.Name(), err)
		}
		if err := releaseSchema.ValidateBytes(manifest); err != nil {
			t.Fatalf("%s manifest.json: %v", e.Name(), err)
		}

		listingsRaw, err := os.ReadFile(filepath.Join(dir, "listings.json"))
		if err != nil {
			t.Fatalf("%s: read listings: %v", e.Name(), err)
		}
		for i, item := range decodeArray(t, e.Name()+"/listings.json", listingsRaw) {
			if err := listingSchema.Validate(item); err != nil {
				t.Fatalf("%s listings[%d]: %v", e.Name(), i, err)
			}
		}

		versionsRaw, err := os.ReadFile(filepath.Join(dir, "versions.json"))
		if err != nil {
			t.Fatalf("%s: read versions: %v", e.Name(), err)
		}
		for i, item := range decodeArray(t, e.Name()+"/versions.json", versionsRaw) {
			if err := versionSchema.Validate(item); err != nil {
				t.Fatalf("%s versions[%d]: %v", e.Name(), i, err)
			}
		}
	}
	if releases == 0 {
		t.Fatalf("no committed releases found under %s", root)
	}
}

