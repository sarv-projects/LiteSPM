// TestSchemaPatternsMatchDomainIdentifiers keeps the schema patterns that
// duplicate a domain identifier grammar in sync with the Go source.
func TestSchemaPatternsMatchDomainIdentifiers(t *testing.T) {
	cases := []struct {
		schema  string
		pointer string
		want    string
	}{
		{"catalog-release.schema.json", "/properties/releaseId/pattern", domain.RegexReleaseID.String()},
		{"source.schema.json", "/properties/sourceId/pattern", domain.RegexSourceID.String()},
		{"listing.schema.json", "/properties/id/pattern", domain.RegexListingID.String()},
		{"version.schema.json", "/properties/listingId/pattern", domain.RegexListingID.String()},
	}
	for _, tc := range cases {
		raw, err := os.ReadFile(filepath.Join("..", "..", "schemas", tc.schema))
		if err != nil {
			t.Fatalf("read %s: %v", tc.schema, err)
		}
		doc, err := schemacheck.Decode(raw)
		if err != nil {
			t.Fatalf("decode %s: %v", tc.schema, err)
		}
		got := pointerString(t, doc, tc.pointer)
		if got != tc.want {
			t.Fatalf("%s%s = %q, want %q (keep the schema and domain regexp in sync)", tc.schema, tc.pointer, got, tc.want)
		}
	}
}

func pointerString(t *testing.T, doc any, pointer string) string {
	t.Helper()
	cur := doc
	for _, tok := range strings.Split(strings.TrimPrefix(pointer, "/"), "/") {
		obj, ok := cur.(map[string]any)
		if !ok {
			t.Fatalf("pointer %s: %q is not an object", pointer, tok)
		}
		cur, ok = obj[tok]
		if !ok {
			t.Fatalf("pointer %s: no key %q", pointer, tok)
		}
	}
	s, ok := cur.(string)
	if !ok {
		t.Fatalf("pointer %s does not hold a string", pointer)
	}
	return s
}

// TestPreFixSchemasRejectRealArtifacts records the evidence that this
// validator is strict enough: the pre-fix subschemas (git 7d96ca1) reject the
// artifacts the code actually emits. Each case is the schema text as committed
// before the alignment.
func TestPreFixSchemasRejectRealArtifacts(t *testing.T) {
	snapshotRaw, err := os.ReadFile(filepath.Join("..", "source", "testdata", "snapshots", "marketplace-630595d24d40", "snapshot.json"))
	if err != nil {
		t.Fatalf("read snapshot record: %v", err)
	}
	var snapshotDoc struct {
		Snapshot json.RawMessage `json:"snapshot"`
	}
	if err := json.Unmarshal(snapshotRaw, &snapshotDoc); err != nil {
		t.Fatalf("decode snapshot record: %v", err)
	}

	cases := []struct {
		name          string
		prefixSchema  string
		artifact      string
		wantSubstring string
	}{
		{
			// catalog-release.schema.json #/properties/releaseId before the fix.
			name:          "catalog-release releaseId",
			prefixSchema:  `{"type":"string","pattern":"^rel_[0-9A-Za-z]{26}$"}`,
			artifact:      `"rel-2026-10-07-01"`,
			wantSubstring: "pattern",
		},
		{
			// source.schema.json #/properties/snapshot before the fix: no
			// sourceId property, additionalProperties false.
			name: "source snapshot",
			prefixSchema: `{"type":"object",
				"properties":{
					"snapshotId":{"type":"string"},
					"adapterVersion":{"type":"string"},
					"upstreamRevision":{"type":["string","null"]},
					"startedAt":{"type":"string"},
					"completedAt":{"type":"string"},
					"status":{"type":"string"},
					"itemCount":{"type":"integer"},
					"cursor":{"type":"string"},
					"contentDigest":{"type":"string"},
					"errorSummary":{"type":["string","null"]}
				},
				"additionalProperties":false}`,
			artifact:      string(snapshotDoc.Snapshot),
			wantSubstring: `unexpected property "sourceId"`,
		},
		{
			// listing.schema.json #/properties/source before the fix required
			// sourceType and manifestFormat, which SourceReference never carries.
			name: "listing source",
			prefixSchema: `{"type":"object",
				"required":["sourceId","upstreamId","sourceType","manifestFormat"],
				"properties":{
					"sourceId":{"type":"string"},
					"upstreamId":{"type":"string"},
					"sourceType":{"type":"string"},
					"sourceUrl":{"type":"string"},
					"manifestFormat":{"type":"string"},
					"manifestSchemaVersion":{"type":"string"}
				}}`,
			artifact:      `{"sourceId":"06ketan","upstreamId":"slideshot","url":"https://github.com/06ketan"}`,
			wantSubstring: `missing required property "sourceType"`,
		},
		{
			// install-plan.schema.json #/properties/effects before the fix: an
			// array of {type,target} objects, while InstallPlan carries strings.
			name:          "install-plan effects",
			prefixSchema:  `{"type":"array","items":{"type":"object","required":["type"],"properties":{"type":{"type":"string"},"target":{"type":"string"}},"additionalProperties":false}}`,
			artifact:      `["package.install","fs:read"]`,
			wantSubstring: "expected type",
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			s := mustParse(t, tc.prefixSchema)
			err := validateJSON(t, s, tc.artifact)
			if err == nil {
				t.Fatalf("pre-fix schema unexpectedly accepted the real artifact")
			}
			if !strings.Contains(err.Error(), tc.wantSubstring) {
				t.Fatalf("error %q does not contain %q", err.Error(), tc.wantSubstring)
			}
		})
	}
}
