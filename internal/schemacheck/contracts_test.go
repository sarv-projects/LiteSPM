// TestSnapshotRecordValidates validates the snapshot section a real store
// wrote (internal/source testdata, produced by scripts/snapshot_store.py and
// loadable by internal/source) against source.schema.json#/properties/snapshot.
func TestSnapshotRecordValidates(t *testing.T) {
	src := loadSchema(t, "source.schema.json")
	sub, err := src.Resolve("/properties/snapshot")
	if err != nil {
		t.Fatalf("Resolve snapshot subschema: %v", err)
	}

	raw, err := os.ReadFile(filepath.Join("..", "source", "testdata", "snapshots", "marketplace-630595d24d40", "snapshot.json"))
	if err != nil {
		t.Fatalf("read snapshot record: %v", err)
	}
	var doc struct {
		Snapshot json.RawMessage `json:"snapshot"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("decode snapshot record: %v", err)
	}
	if len(doc.Snapshot) == 0 {
		t.Fatalf("snapshot record has no snapshot section")
	}
	if err := sub.ValidateBytes(doc.Snapshot); err != nil {
		t.Fatalf("snapshot section: %v", err)
	}
}

